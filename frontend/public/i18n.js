const LANGUAGE_LABELS = { en: "EN", ru: "RU", uk: "UA" };

function applyLanguage(language) {
  const lang = VELMONTAIRE_TRANSLATIONS[language] ? language : "en";
  const dict = VELMONTAIRE_TRANSLATIONS[lang];

  document.documentElement.lang = lang === "uk" ? "uk" : lang;

  document.querySelectorAll("[data-i18n]").forEach((node) => {
    const value = dict[node.dataset.i18n];
    if (value !== undefined) node.textContent = value;
  });

  document.querySelectorAll("[data-i18n-html]").forEach((node) => {
    const value = dict[node.dataset.i18nHtml];
    if (value !== undefined) node.innerHTML = value;
  });

  const current = document.querySelector("#language-current");
  if (current) current.textContent = LANGUAGE_LABELS[lang];

  document.querySelectorAll("[data-language]").forEach((node) => {
    node.classList.toggle("active", node.dataset.language === lang);
  });

  localStorage.setItem("velmontaire_language", lang);
}

function initLanguageSwitcher() {
  const button = document.querySelector("#language-button");
  const menu = document.querySelector("#language-menu");
  if (!button || !menu) return;

  const saved = localStorage.getItem("velmontaire_language");
  const browser = (navigator.language || "en").toLowerCase();
  const initial = saved || (browser.startsWith("ru") ? "ru" : browser.startsWith("uk") ? "uk" : "en");
  applyLanguage(initial);

  button.addEventListener("click", () => {
    const open = !menu.hidden;
    menu.hidden = open;
    button.setAttribute("aria-expanded", String(!open));
  });

  menu.querySelectorAll("[data-language]").forEach((option) => {
    option.addEventListener("click", () => {
      applyLanguage(option.dataset.language);
      menu.hidden = true;
      button.setAttribute("aria-expanded", "false");
    });
  });

  document.addEventListener("click", (event) => {
    if (!event.target.closest("#language-switcher")) {
      menu.hidden = true;
      button.setAttribute("aria-expanded", "false");
    }
  });
}

document.addEventListener("DOMContentLoaded", initLanguageSwitcher);
